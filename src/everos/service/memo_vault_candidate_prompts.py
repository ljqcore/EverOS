def native_prompt_in_chinese(prompt: str) -> str:
    """Keep native extraction semantics while replacing its language policy."""
    import re
    language_rule = (
        "**CRITICAL LANGUAGE RULE**: 标题、描述、摘要、标签和情节正文必须使用中文。"
        "专有名词、产品名、代码标识符和路径保留原语言；证据摘录保留原文。"
        "本规则取代跟随输入语言或已有画像语言的要求。"
    )
    result = re.sub(r"\*\*CRITICAL LANGUAGE RULE\*\*:.*?(?=\n\n|$)",
                    lambda match: language_rule, prompt, flags=re.DOTALL)
    return result + "\n\n" + language_rule
